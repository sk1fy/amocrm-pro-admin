export function getMarketWidget(filter: string) {
  const code = filter.split(':')[0]
  return (
    marketWidgets.find((widget) => widget.code === code) ??
    (Object.hasOwn(legacyMarketWidgets, code) ? legacyMarketWidgets[code] : undefined)
  )
}

export function getMarketAccounts(filter: string): readonly string[] {
  const widget = getMarketWidget(filter)
  if (!widget) return []
  return (filter.endsWith(':removed') ? widget.removed : widget.accounts).map(String)
}
